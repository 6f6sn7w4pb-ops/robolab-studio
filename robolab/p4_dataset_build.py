"""Collect, verify and index a planned P4 OSC dataset.

Each worker process owns one Engine and records its shard of the plan. Every episode is
verified right after recording (file hashes, image/action/contact alignment and an exact
replay of the saved actions through a fresh controller). Indexing reads only those files.
"""
from collections import Counter
from dataclasses import asdict
import hashlib
import json
from pathlib import Path
import shutil
import time
import traceback

from .contact_store import canonical_json
from .p4_dataset import DEV_SPLITS, SPLITS, audit_plan, plan_document

INDEX_SCHEMA = 'robolab.p4_dataset_index.v1'
CHECK_SCHEMA = 'robolab.p4_dataset_episode_check.v1'
CHECK_FILE = 'verification.json'
OBSTACLE_MOVED_M = .002
OBSTACLE_JOINT = 'p4_distractor_joint'
TARGET_JOINT = 'p4_stepped_bar_joint'
# Before the hand starts closing, the object must stay where it rested: a roll-over or a knock by
# any robot link (the contact sampler only sees the fingers) makes the demonstration unusable.
PREGRASP_ROTATION_DEG = 1.
PREGRASP_MOVE_M = .001
COMPARED_FILES = ('manifest.json', 'actions_and_contacts.jsonl', 'frames.jsonl', 'model.xml')
# v2: obstacle motion is measured from its rested pose at the end of the settle phase; the
# initial 1 mm drop onto the floor is reported separately instead of counting as a push.
# v3: adds the pre-grasp target disturbance check.
METRICS_VERSION = 3


def sha256_file(path):
    digest = hashlib.sha256()
    with path.open('rb') as stream:
        for chunk in iter(lambda: stream.read(1024*1024), b''):
            digest.update(chunk)
    return digest.hexdigest()


def digest(value):
    return hashlib.sha256(canonical_json(value)).hexdigest()


def publish_json(path, value):
    temporary = path.with_name(path.name+'.tmp')
    temporary.write_bytes(canonical_json(value)+b'\n')
    temporary.replace(path)


def read_json(path):
    return json.loads(path.read_bytes())


def load_plan(root):
    """Regenerate the plan from code and seed; refuse a directory written by a different plan."""
    stored = read_json(root/'plan.json')
    document, cases, controls = plan_document(stored['plan'], **({'seed': stored['seed']} if stored['seed'] else {}))
    if document['plan_sha256'] != stored['plan_sha256']:
        raise ValueError('plan.json differs from the plan generated by this code; use a new output directory')
    return document, cases, controls


def ordered_cases(cases, controls):
    return list(cases)+list(controls)


def episode_metrics(model, manifest, trace, frames):
    """Measurements outside the contact sampler: obstacle motion, action saturation, TCP clearance."""
    import numpy as np

    adr = int(model.joint(OBSTACLE_JOINT).qposadr[0])
    start = np.asarray(manifest['initial']['qpos'][adr:adr+3])
    settle = [index for index, row in enumerate(trace) if row['phase'] == 'settle']
    if not settle or settle != list(range(len(settle))):
        raise ValueError('Episode does not begin with a contiguous settle phase')
    rested = np.asarray(trace[settle[-1]]['qpos_after'][adr:adr+3])
    moved = max((float(np.linalg.norm(np.asarray(row['qpos_after'][adr:adr+3])-rested)) for row in trace[len(settle):]),
                default=0.)
    import mujoco

    target = int(model.joint(TARGET_JOINT).qposadr[0])
    close = next((index for index, row in enumerate(trace) if row['phase'] == 'close'), len(trace))
    reference = np.asarray(trace[settle[-1]]['qpos_after'][target:target+7])
    rotation_ref, rotation = np.zeros(9), np.zeros(9)
    mujoco.mju_quat2Mat(rotation_ref, reference[3:])
    pregrasp_angle = pregrasp_move = 0.
    onset = None
    for index in range(len(settle), close):
        pose = np.asarray(trace[index]['qpos_after'][target:target+7])
        mujoco.mju_quat2Mat(rotation, pose[3:])
        cosine = (np.trace(rotation_ref.reshape(3, 3).T @ rotation.reshape(3, 3))-1)/2
        angle = float(np.degrees(np.arccos(np.clip(cosine, -1., 1.))))
        move = float(np.linalg.norm(pose[:3]-reference[:3]))
        if onset is None and (angle >= PREGRASP_ROTATION_DEG or move >= PREGRASP_MOVE_M):
            onset = index
        pregrasp_angle, pregrasp_move = max(pregrasp_angle, angle), max(pregrasp_move, move)
    actions = np.asarray([row['action_normalized_7d'] for row in trace], dtype=float)
    saturated = np.any(np.abs(actions[:, :6]) >= 1., axis=1)
    distances = [abs(frame['nearest_obstacle']['signed_distance_m']) for frame in frames]
    target_contact = sum(any(c['pair_role'] == 'finger_target' and c['load_bearing'] for c in row['sample']['contacts'])
                         for row in trace)
    return dict(metrics_version=METRICS_VERSION, ticks=len(trace), obstacle_max_displacement_m=moved,
                obstacle_settle_offset_m=float(np.linalg.norm(rested-start)), settle_ticks=len(settle),
                pregrasp_ticks=close-len(settle), pregrasp_target_rotation_deg=pregrasp_angle,
                pregrasp_target_displacement_m=pregrasp_move, pregrasp_disturbance_onset_tick=onset,
                saturated_action_ticks=int(saturated.sum()),
                action_min=actions.min(axis=0).tolist(), action_max=actions.max(axis=0).tolist(),
                min_tcp_surface_distance_m=min(distances),
                nearest_surface_counts=dict(Counter(frame['nearest_obstacle']['geom'] for frame in frames)),
                finger_target_contact_ticks=int(target_contact))


def failure_reasons(case, outcome, metrics):
    reasons = []
    if not outcome['lifted']:
        reasons.append('not_lifted')
    if case.part not in outcome['held_parts']:
        reasons.append('requested_part_not_held')
    if set(outcome['held_parts'])-{case.part}:
        reasons.append('other_part_held')
    if outcome['finger_obstacle_frames']:
        reasons.append('finger_obstacle_contact')
    if metrics['obstacle_max_displacement_m'] >= OBSTACLE_MOVED_M:
        reasons.append('obstacle_moved')
    if pregrasp_disturbed(metrics):
        reasons.append('object_moved_before_grasp')
    return reasons


def pregrasp_disturbed(metrics):
    return (metrics['pregrasp_target_rotation_deg'] >= PREGRASP_ROTATION_DEG
            or metrics['pregrasp_target_displacement_m'] >= PREGRASP_MOVE_M)


def expected_outcome(case, outcome, metrics):
    if case.expected == 'success':
        return (outcome['passed'] and outcome['held_parts'] == [case.part]
                and metrics['obstacle_max_displacement_m'] < OBSTACLE_MOVED_M and not pregrasp_disturbed(metrics))
    return not outcome['passed'] and (outcome['finger_obstacle_frames'] > 0
                                      or metrics['obstacle_max_displacement_m'] >= OBSTACLE_MOVED_M)


def collect_case(engine, root, case, *, subdir='episodes', preview=True):
    from .p4_osc_recording import FRAMES, TRACE, run_osc_episode, verify_osc_episode

    directory = root/subdir/case.case_id
    check = dict(schema=CHECK_SCHEMA, case_id=case.case_id, status='error', files_verified=False)
    started = time.monotonic()
    try:
        run_osc_episode(engine, directory, case.scene, case.part, case.instruction)
        recorded = time.monotonic()
        manifest, frames, replay = verify_osc_episode(engine, directory, case.scene)
        if manifest['instruction'] != case.instruction:
            raise ValueError('Recorded instruction differs from the plan')
        trace = [json.loads(line) for line in (directory/TRACE).read_bytes().splitlines()]
        if len(frames) != len(trace) or [json.loads(line) for line in (directory/FRAMES).read_bytes().splitlines()] != frames:
            raise ValueError('Frame file changed during verification')
        metrics = episode_metrics(engine.model, manifest, trace, frames)
        outcome = manifest['outcome']
        if preview and manifest['representative_sample_index'] is not None:
            _save_preview(directory, frames[manifest['representative_sample_index']])
        check.update(status='verified', files_verified=True, replay=replay, metrics=metrics,
                     expected_outcome_verified=expected_outcome(case, outcome, metrics),
                     failure_reasons=failure_reasons(case, outcome, metrics),
                     record_wall_s=round(recorded-started, 3), verify_wall_s=round(time.monotonic()-recorded, 3))
    except Exception as error:
        check.update(error=str(error), traceback=traceback.format_exc())
    if directory.is_dir():
        publish_json(directory/CHECK_FILE, check)
    return check


def _save_preview(directory, frame):
    import sys
    scripts = Path(__file__).resolve().parents[1]/'scripts'
    if str(scripts) not in sys.path:
        sys.path.insert(0, str(scripts))
    from verify_p4_parts import save_projection_preview
    save_projection_preview(directory, frame)


def run_worker(root, case_ids, *, subdir='episodes', stop=lambda: False, log=print):
    """Record the given cases with one engine, skipping episodes already verified."""
    from .engine import Engine

    _, cases, controls = load_plan(root)
    lookup = {case.case_id: case for case in ordered_cases(cases, controls)}
    engine = Engine()
    try:
        for case_id in case_ids:
            if stop():
                log(json.dumps(dict(event='stopped', case_id=case_id)))
                break
            case = lookup[case_id]
            directory = root/subdir/case_id
            if (directory/CHECK_FILE).is_file() and read_json(directory/CHECK_FILE).get('status') == 'verified':
                log(json.dumps(dict(event='skip_verified', case_id=case_id)))
                continue
            if directory.exists():
                # Keep interrupted or failed attempts for inspection instead of deleting them.
                archive = root/'discarded'
                archive.mkdir(exist_ok=True)
                serial = sum(1 for _ in archive.glob(f'{subdir}-{case_id}-*'))
                shutil.move(str(directory), archive/f'{subdir}-{case_id}-{serial}')
            check = collect_case(engine, root, case, subdir=subdir)
            outcome = {}
            if check['files_verified']:
                outcome = read_json(directory/'manifest.json')['outcome']
            log(json.dumps(dict(event='episode', case_id=case_id, status=check['status'],
                                passed=outcome.get('passed'), expected=check.get('expected_outcome_verified'),
                                reasons=check.get('failure_reasons'), wall_s=(check.get('record_wall_s') or 0)
                                +(check.get('verify_wall_s') or 0), error=check.get('error'))))
    finally:
        engine.close()


def compare_recollection(root, case_id, subdir='recheck'):
    """Byte comparison of a re-collected episode with the original recording."""
    return compare_episode_dirs(root/'episodes'/case_id, root/subdir/case_id)


def compare_with_dataset(root, other):
    """Compare every episode whose planned scene is identical in another dataset directory."""
    _, cases, controls = load_plan(root)
    other_plan = read_json(other/'plan.json')
    other_scenes = {item['case_id']: item for item in other_plan['cases']+other_plan['controls']}
    rows, skipped = [], []
    for case in ordered_cases(cases, controls):
        previous = other_scenes.get(case.case_id)
        same_scene = previous is not None and (canonical_json(previous['scene']) == canonical_json(asdict(case.scene))
                                               and previous['instruction'] == case.instruction)
        if not same_scene:
            skipped.append(case.case_id)
            continue
        rows.append(compare_episode_dirs(root/'episodes'/case.case_id, other/'episodes'/case.case_id))
    return dict(other=str(other), other_plan_sha256=other_plan['plan_sha256'], compared=len(rows),
                identical=sum(row['identical'] for row in rows), images_compared=sum(row['images_compared'] for row in rows),
                skipped_changed_scenes=skipped, differing=[row for row in rows if not row['identical']])


def compare_episode_dirs(first, second):
    case_id = first.name
    differing = [name for name in COMPARED_FILES if sha256_file(first/name) != sha256_file(second/name)]
    images = sorted(path.name for path in (first/'rgb').iterdir())
    if images != sorted(path.name for path in (second/'rgb').iterdir()):
        differing.append('rgb/(file list)')
    else:
        differing += ['rgb/'+name for name in images
                      if sha256_file(first/'rgb'/name) != sha256_file(second/'rgb'/name)]
    return dict(case_id=case_id, identical=not differing, differing=differing[:20], images_compared=len(images))


def _quadrant(yaw, part):
    # Direction of the requested part from the object origin, in 90-degree world sectors.
    heading = (yaw+(180. if part == 'thick' else 0.)) % 360.
    return int(heading//90)


def recompute_metrics(directory, manifest):
    """Derive current-version metrics from the recorded files (no simulation)."""
    import mujoco

    model = mujoco.MjModel.from_xml_path(str(directory/'model.xml'))
    trace = [json.loads(line) for line in (directory/'actions_and_contacts.jsonl').read_bytes().splitlines()]
    frames = [json.loads(line) for line in (directory/'frames.jsonl').read_bytes().splitlines()]
    return episode_metrics(model, manifest, trace, frames)


def build_index(root, *, elapsed_wall_s=None, recheck=None, status=None):
    plan, cases, controls = load_plan(root)
    runs = []
    for case in ordered_cases(cases, controls):
        directory = root/'episodes'/case.case_id
        row = dict(path=f'episodes/{case.case_id}', case_id=case.case_id, scene_id=case.scene.scene_id,
                   family=case.scene.family, split=case.split, part=case.part, phrasing=case.phrasing,
                   held_out_phrasing=case.phrasing == 'held_out', expected=case.expected,
                   instruction=dict(en=case.instruction_en, zh=case.instruction_zh),
                   requested_part_sector=_quadrant(case.scene.yaw_deg, case.part), files_verified=False)
        check = read_json(directory/CHECK_FILE) if (directory/CHECK_FILE).is_file() else None
        if check is None:
            row['status'] = 'missing'
        elif check['status'] != 'verified':
            row.update(status='error', error=check.get('error'))
        else:
            manifest = read_json(directory/'manifest.json')
            for name, key in (('actions_and_contacts.jsonl', 'trace_sha256'), ('frames.jsonl', 'frames_sha256'),
                              ('model.xml', 'model_xml_sha256')):
                if sha256_file(directory/name) != manifest[key]:
                    raise ValueError(f'{case.case_id}: {name} changed after verification')
            if canonical_json(manifest['scene']) != canonical_json(asdict(case.scene)):
                raise ValueError(f'{case.case_id}: recorded scene differs from the plan')
            replay = check['replay']
            metrics, recomputed = check['metrics'], False
            if metrics.get('metrics_version') != METRICS_VERSION:
                metrics, recomputed = recompute_metrics(directory, manifest), True
            row.update(status='verified', files_verified=replay['max_qpos_difference'] == 0
                       and replay['contact_samples_equal'], outcome=manifest['outcome'], rgb_pairs=manifest['rgb_pairs'],
                       replay=replay, metrics=metrics, metrics_recomputed_from_files=recomputed,
                       failure_reasons=failure_reasons(case, manifest['outcome'], metrics),
                       expected_outcome_verified=expected_outcome(case, manifest['outcome'], metrics),
                       model_xml_sha256=manifest['model_xml_sha256'], initial_state_sha256=digest(manifest['initial']),
                       manifest_sha256=sha256_file(directory/'manifest.json'))
        runs.append(row)
    indexed = [row for row in runs if row['split'] != 'control']
    audit = dict(plan=audit_plan(cases, controls), problems=[])
    by_scene = {}
    for row in indexed:
        by_scene.setdefault(row['scene_id'], []).append(row)
    verified_scenes = [group for group in by_scene.values() if all(row['files_verified'] for row in group)]
    for group in verified_scenes:
        for key in ('model_xml_sha256', 'initial_state_sha256'):
            if group[0][key] != group[1][key]:
                audit['problems'].append(f'{group[0]["scene_id"]}: paired episodes differ in {key}')
    xml_owner = {}
    for group in verified_scenes:
        owner = xml_owner.setdefault(group[0]['model_xml_sha256'], group[0]['scene_id'])
        if owner != group[0]['scene_id']:
            audit['problems'].append(f'{owner} and {group[0]["scene_id"]} share one scene XML')
    splits = {}
    for split in SPLITS:
        rows = [row for row in indexed if row['split'] == split]
        good = [row for row in rows if row['files_verified'] and row['expected_outcome_verified']]
        splits[split] = dict(
            attempts=len(rows), verified=sum(row['files_verified'] for row in rows), successes=len(good),
            failures=len(rows)-len(good),
            failure_reasons=dict(Counter(reason for row in rows for reason in row.get('failure_reasons', []))),
            by_family={family: sum(row['family'] == family for row in good)
                       for family in sorted({row['family'] for row in rows})},
            by_part={part: sum(row['part'] == part for row in good) for part in ('thick', 'thin')},
            by_phrasing={kind: sum(row['phrasing'] == kind for row in good) for kind in ('seen', 'held_out')},
            requested_part_sectors=dict(sorted(Counter(row['requested_part_sector'] for row in good).items())),
            successful_paths=[row['path'] for row in good])
    controls_rows = [row for row in runs if row['split'] == 'control']
    verified_rows = [row for row in runs if row['files_verified']]
    saturation = sum(row['metrics']['saturated_action_ticks'] for row in verified_rows)
    ticks = sum(row['metrics']['ticks'] for row in verified_rows)
    totals = dict(
        planned=len(runs), indexed_attempts=len(indexed), controls=len(controls_rows),
        verified=len(verified_rows), successful_demos=sum(item['successes'] for item in splits.values()),
        controls_failed_as_expected=sum(row['files_verified'] and row['expected_outcome_verified'] for row in controls_rows),
        rgb_pairs=sum(row.get('rgb_pairs', 0) for row in verified_rows), action_ticks=ticks,
        saturated_action_ticks=saturation,
        max_replay_qpos_difference=max((row['replay']['max_qpos_difference'] for row in verified_rows), default=None),
        max_obstacle_displacement_success_m=max((row['metrics']['obstacle_max_displacement_m'] for row in indexed
                                                  if row['files_verified'] and row['expected_outcome_verified']),
                                                 default=None))
    complete = totals['verified'] == totals['planned']
    gate = dict(all_planned_episodes_verified=complete,
                exact_replay=complete and totals['max_replay_qpos_difference'] == 0,
                controls_failed_as_expected=totals['controls_failed_as_expected'] == totals['controls'],
                split_audit_clean=not audit['problems'],
                every_split_has_demos=all(splits[split]['successes'] > 0 for split in SPLITS if splits[split]['attempts']),
                recollection_identical=None if recheck is None else all(item['identical'] for item in recheck))
    index = dict(schema=INDEX_SCHEMA, status=status or ('finalized' if complete else 'verification_error'),
                 plan=plan['plan'], plan_sha256=plan['plan_sha256'], seed=plan['seed'], is_vla=False,
                 teacher='simulator_geometry_rule_osc', dataset_ready=False, splits=splits, totals=totals,
                 audit=audit, recheck=recheck, gate=gate, runs=runs, elapsed_wall_s=elapsed_wall_s,
                 dev_splits=list(DEV_SPLITS))
    index['passed'] = all(value is not False for value in gate.values()) and gate['recollection_identical'] is not None
    # Raw teacher episodes become a training view only after export; the index never claims more.
    return index
